export type DictKey = keyof typeof FR;

const DICTS: Record<Locale, Record<DictKey, string>> = { fr: FR, en: EN };

type I18nValue = {
  locale: Locale;
  setLocale: (next: Locale) => void;
  t: (key: DictKey) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

export function LocaleProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("fr");

  useEffect(() => {
    void SecureStore.getItemAsync(LOCALE_KEY)
      .then((stored) => {
        if (stored === "en" || stored === "fr") setLocaleState(stored);
      })
      .catch(() => {});
  }, []);

  const setLocale = useCallback((next: Locale) => {
    setLocaleState(next);
    void SecureStore.setItemAsync(LOCALE_KEY, next).catch(() => {});
  }, []);

  const t = useCallback((key: DictKey) => DICTS[locale][key] ?? FR[key], [locale]);

  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within LocaleProvider");
  return ctx;
}

export function bookingStatusLabel(locale: Locale, status: string) {
  const map: Record<string, DictKey> = {
    PROPOSED: "status_proposed",
    AWAITING_PAYMENT: "status_awaiting_payment",
    ACCEPTED: "status_accepted",
    HANDED_OVER: "status_handed_over",
    IN_TRANSIT: "status_in_transit",
    DELIVERED: "status_delivered",
    CANCELLED: "status_cancelled",
    REFUSED: "status_refused",
  };
  const key = map[status];
  return key ? DICTS[locale][key] : status;
}
